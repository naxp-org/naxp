/**
 * Writes the standard naxps into each library as source, from `naxp-standards.json` beside this
 * script, so that no library reads JSON at run time and the R package's vendored amalgamation
 * carries them with nothing more.
 *
 *     node standards/generate.js [--check]
 *
 * Three files are written, one row per variant in the order of the file, each default first:
 *
 *   src/cpp/src/standard_table.hpp    included by naxp.cpp, and so by the amalgamation
 *   src/js/lib/standard-table.js
 *   src/cs/Naxp/StandardTable.g.cs
 *
 * A row is the standard's id and name, the variant's id, the naxp and the notes. The examples
 * are test data and stay in the file.
 *
 * A fourth, src/cs/Naxp/StandardNaxp.g.cs, holds each naxp again as a C# constant, because an
 * attribute argument must be one: StandardNaxp.UKPostcode.PaddingTolerant is the variant
 * padding-tolerant of uk-postcode. The names come from the ids, so they are frozen with them.
 *
 * With --check nothing is written: the run fails, naming each file that is not what it would
 * write. The JavaScript tests and the release workflow both run it, so a file edited without
 * regenerating is caught. Lines end in LF, and a CR in the working copy is ignored when checking.
 */

import { readFileSync, writeFileSync } from 'node:fs';
import { dirname, join, resolve } from 'node:path';
import { fileURLToPath } from 'node:url';

const here = dirname(fileURLToPath(import.meta.url));
const root = resolve(here, '..');

const banner = [
	'Copyright (c) Tim Gordon.',
	'This file is licensed to you under the Apache Licence, Version 2.0. See the LICENSE file.',
	'',
	'Generated by standards/generate.js from standards/naxp-standards.json. Do not edit.',
];

/**
 * The rows the libraries carry, read from the standards file.
 *
 * @param {string} [file] The standards file; by default the one beside this script.
 * @returns {{id: string, name: string, variant: string, pattern: string, notes: string}[]}
 */
export function readRows(file = join(here, 'naxp-standards.json')) {
	const data = JSON.parse(readFileSync(file, 'utf8'));

	return data.standards.flatMap((standard) => standard.variants.map((variant) => ({
		id: standard.id,
		name: standard.name,
		variant: variant.id,
		pattern: variant.naxp,
		notes: variant.notes,
	})));
}

/**
 * A string as a literal in C++, C# or JavaScript, which escape alike for what the file may
 * hold: printable ASCII and a newline.
 */
function literal(text, quote) {
	if (!/^[\x20-\x7E\n]*$/.test(text)) {
		throw new Error(`Only printable ASCII and newlines may go into a library: ${JSON.stringify(text)}`);
	}

	const escaped = text
		.replaceAll('\\', '\\\\')
		.replaceAll(quote, `\\${quote}`)
		.replaceAll('\n', '\\n');

	return `${quote}${escaped}${quote}`;
}

/** Lines as `//` comments, a blank line staying blank. */
function comment(lines) {
	return lines.map((line) => (line === '' ? '' : `// ${line}`));
}

const fields = ['id', 'name', 'variant', 'pattern', 'notes'];

function cpp(rows) {
	const lines = [
		...comment(banner),
		'',
		'#ifndef NAXP_STANDARD_TABLE_HPP',
		'#define NAXP_STANDARD_TABLE_HPP',
		'',
		'#include "naxp/naxp.hpp"',
		'',
		'namespace logmu::detail',
		'{',
		'\t/// The standard naxps, one row per variant, each standard\'s default first.',
		'\tinline constexpr standard_naxp_variant standard_table[] =',
		'\t{',
	];

	rows.forEach((row, index) => {
		lines.push('\t\t{');
		fields.forEach((field, at) => {
			lines.push(`\t\t\t${literal(row[field], '"')}${at < fields.length - 1 ? ',' : ''}`);
		});
		lines.push(`\t\t}${index < rows.length - 1 ? ',' : ''}`);
	});

	lines.push('\t};', '}', '', '#endif');

	return lines;
}

function javascript(rows) {
	const lines = [
		...comment(banner),
		'',
		'/**',
		' * The standard naxps, one row per variant, each standard\'s default first.',
		' *',
		' * @type {ReadonlyArray<Readonly<{id: string, name: string, variant: string, pattern: string,',
		' * notes: string}>>}',
		' */',
		'export const standardTable = Object.freeze([',
	];

	for (const row of rows) {
		lines.push('\tObject.freeze({');
		for (const field of fields) { lines.push(`\t\t${field}: ${literal(row[field], '\'')},`); }
		lines.push('\t}),');
	}

	lines.push(']);');

	return lines;
}

function csharp(rows) {
	const lines = [
		...comment(banner),
		'',
		'using System.Collections.Immutable;',
		'',
		'namespace LogMu;',
		'',
		'static class StandardTable',
		'{',
		'\t/// <summary>',
		'\t/// The standard naxps, one row per variant, each standard\'s default first.',
		'\t/// </summary>',
		'\tinternal static readonly ImmutableArray<StandardNaxpVariant> Rows =',
		'\t[',
	];

	for (const row of rows) {
		lines.push('\t\tnew StandardNaxpVariant(');
		fields.forEach((field, at) => {
			lines.push(`\t\t\t${literal(row[field], '"')}${at < fields.length - 1 ? ',' : '),'}`);
		});
	}

	lines.push('\t];', '}');

	return lines;
}

/**
 * The parts of an id that are acronyms, and so go into a C# name in capitals, as .NET writes
 * `IO`. Every other part is capitalised, so `no-separator` is `NoSeparator`. Adding or removing
 * an entry renames every published constant with that part, so neither may happen once it is in
 * use.
 */
const acronyms = new Set(['uk', 'nl']);

/**
 * An id as a C# name: `uk-postcode` is `UKPostcode`. The site uses it too, to show the constant
 * a naxp matches on /code-gen/.
 */
export function csharpName(id) {
	const name = id
		.split('-')
		.map((part) => (acronyms.has(part) ? part.toUpperCase() : `${part[0].toUpperCase()}${part.slice(1)}`))
		.join('');

	if (!/^[A-Z][A-Za-z0-9]*$/.test(name)) {
		throw new Error(`The id ${id} gives ${name}, which is not a C# name`);
	}

	return name;
}

/** A naxp as a C# verbatim string, the way a naxp is written in the [Naxp] attribute. */
function verbatim(text) {
	if (!/^[\x20-\x7E]*$/.test(text)) {
		throw new Error(`Only printable ASCII may go into a C# constant: ${JSON.stringify(text)}`);
	}

	return `@"${text.replaceAll('"', '""')}"`;
}

/**
 * Notes as the lines of an XML documentation comment: backticks become <c>, ** becomes <b>, *
 * becomes <i>, and a newline becomes <br/>.
 */
function xmlDoc(notes) {
	const escape = (text) => text.replaceAll('&', '&amp;').replaceAll('<', '&lt;').replaceAll('>', '&gt;');
	const lines = notes.split('\n');

	return lines.map((line, index) => {
		const pieces = line.split('`');

		if (pieces.length % 2 === 0) { throw new Error(`Unbalanced backtick in the notes: ${line}`); }

		const xml = pieces.map((piece, at) => {
			if (at % 2 === 1) { return `<c>${escape(piece)}</c>`; }

			const marked = escape(piece)
				.replace(/\*\*(.+?)\*\*/g, '<b>$1</b>')
				.replace(/\*(.+?)\*/g, '<i>$1</i>');

			if (marked.includes('*')) { throw new Error(`Unbalanced * in the notes: ${line}`); }

			return marked;
		}).join('');

		return index < lines.length - 1 ? `${xml}<br/>` : xml;
	});
}

function csharpConstants(rows) {
	const lines = [
		...comment(banner),
		'',
		'namespace LogMu;',
		'',
		'/// <summary>',
		'/// The standard naxps listed at https://naxp.org/standard/, one class per standard and one',
		'/// constant per variant, for where C# needs a constant, such as the <c>[Naxp]</c> attribute.',
		'/// </summary>',
		'/// <remarks>',
		'/// A published naxp never changes, so a constant compiled into another assembly stays right.',
		'/// <see cref="Naxp.StandardNaxp"/> finds the same naxps by id at run time.',
		'/// </remarks>',
		'public static class StandardNaxp',
		'{',
	];

	const standards = Map.groupBy(rows, (row) => row.id);
	const names = new Set(['StandardNaxp']);
	let first = true;

	for (const [id, variants] of standards) {
		const name = csharpName(id);

		if (names.has(name)) { throw new Error(`The id ${id} gives ${name}, which is already in use`); }
		names.add(name);

		if (!first) { lines.push(''); }
		first = false;

		// Hovering over a constant shows its own summary alone, so each one repeats this.
		const heading = `${xmlDoc(variants[0].name)[0]}, the standard naxp <c>${id}</c>`;

		lines.push(
			`\t/// <summary>${heading}.</summary>`,
			`\tpublic static class ${name}`,
			'\t{',
		);

		const members = new Set([name]);

		variants.forEach((row, index) => {
			const member = csharpName(row.variant);

			if (members.has(member)) { throw new Error(`The variant ${id} ${row.variant} gives ${member}, which is already in use`); }
			members.add(member);

			if (index > 0) { lines.push(''); }

			lines.push(
				'\t\t/// <summary>',
				`\t\t/// ${heading}, variant <c>${row.variant}</c>.`,
				'\t\t/// <para>',
				...xmlDoc(row.notes).map((line) => `\t\t/// ${line}`),
				'\t\t/// </para>',
				'\t\t/// </summary>',
				`\t\tpublic const string ${member} = ${verbatim(row.pattern)};`,
			);
		});

		lines.push('\t}');
	}

	lines.push('}');

	return lines;
}

/**
 * Every file this writes, by path from the repository root, with its text.
 *
 * @param {ReturnType<typeof readRows>} [rows] The rows; by default those of the standards file.
 * @returns {Map<string, string>}
 */
export function generate(rows = readRows()) {
	return new Map([
		['src/cpp/src/standard_table.hpp', cpp(rows)],
		['src/js/lib/standard-table.js', javascript(rows)],
		['src/cs/Naxp/StandardTable.g.cs', csharp(rows)],
		['src/cs/Naxp/StandardNaxp.g.cs', csharpConstants(rows)],
	].map(([path, lines]) => [path, `${lines.join('\n')}\n`]));
}

/**
 * The files that are not what `generate` would write, by path from the repository root.
 *
 * @returns {string[]}
 */
export function findStale() {
	const stale = [];

	for (const [path, text] of generate()) {
		let current;

		try {
			current = readFileSync(join(root, path), 'utf8').replaceAll('\r\n', '\n');
		} catch {
			current = null;
		}

		if (current !== text) { stale.push(path); }
	}

	return stale;
}

if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
	const flags = process.argv.slice(2);

	if (flags.length > 1 || (flags.length === 1 && flags[0] !== '--check')) {
		console.error('Usage: node standards/generate.js [--check]');
		process.exit(2);
	}

	if (flags[0] === '--check') {
		const stale = findStale();

		if (stale.length > 0) {
			console.error('Out of date with standards/naxp-standards.json; run node standards/generate.js:');
			for (const path of stale) { console.error(`  ${path}`); }
			process.exit(1);
		}

		console.log('The standard naxps in every library match standards/naxp-standards.json.');
	} else {
		for (const [path, text] of generate()) {
			writeFileSync(join(root, path), text);
			console.log(`Wrote ${path}`);
		}
	}
}
